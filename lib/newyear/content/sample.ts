/** 주어진 칸들에 표본 문구를 채운다. 못 찾은 칸은 missing 으로 돌려준다. */
export function sampleValues(product: ProductKey, fields?: SpecField[]): { values: FieldValues; missing: string[] } {
  const all = getSpec(product).fields.filter((f) => f.src === "ai");
  const used = new Map<string, number>();
  const table = new Map<string, string[]>(S[product].map(([page, hint, values]) => [`${page}|${hint}`, values]));
  const values: FieldValues = {}, missing: string[] = [];
  const want = fields ? new Set(fields.map((f) => f.key)) : null;
  for (const f of all) {
    const id = `${f.page}|${f.hint}`;
    const i = used.get(id) ?? 0;
    used.set(id, i + 1);
    if (want && !want.has(f.key)) continue;
    const v = table.get(id)?.[i];
    if (v) values[f.key] = v; else missing.push(`${f.key}(${id})`);
  }
  return { values, missing };
}
